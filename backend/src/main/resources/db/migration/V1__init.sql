-- ARGUS initial schema (Spring Boot 3.5 / Hibernate 6.6 model).
-- Portable across PostgreSQL 15+ and H2 2.x in PostgreSQL compatibility mode.
-- Application data (users, roles, agents) is seeded by com.argus.seed.DataSeeder.

-- ---------------------------------------------------------------- identity & RBAC

CREATE TABLE app_users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        VARCHAR(64)  NOT NULL,
    password_hash   VARCHAR(100) NOT NULL,
    display_name    VARCHAR(80)  NOT NULL,
    enabled         BOOLEAN      NOT NULL,
    failed_attempts INTEGER      NOT NULL,
    lock_until      TIMESTAMP WITH TIME ZONE,
    token_version   INTEGER      NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    last_login_at   TIMESTAMP WITH TIME ZONE
);
CREATE UNIQUE INDEX uq_app_users_username ON app_users (username);

CREATE TABLE user_roles (
    user_id BIGINT    NOT NULL REFERENCES app_users (id),
    role    VARCHAR(32) NOT NULL,
    PRIMARY KEY (user_id, role)
);

CREATE TABLE permissions (
    code        VARCHAR(64)  NOT NULL PRIMARY KEY,
    description VARCHAR(200) NOT NULL
);

CREATE TABLE roles (
    name        VARCHAR(32)  NOT NULL PRIMARY KEY,
    description VARCHAR(200)
);

CREATE TABLE role_permissions (
    role       VARCHAR(32)  NOT NULL REFERENCES roles (name),
    permission VARCHAR(64)  NOT NULL,
    PRIMARY KEY (role, permission)
);

-- ---------------------------------------------------------------- agents & policy

CREATE TABLE agents (
    id                  VARCHAR(40)  NOT NULL PRIMARY KEY,
    name                VARCHAR(80)  NOT NULL,
    icon                VARCHAR(8),
    role_title          VARCHAR(80)  NOT NULL,
    description         VARCHAR(400),
    clearance           INTEGER      NOT NULL,
    status              VARCHAR(16)  NOT NULL,
    last_risk           INTEGER      NOT NULL,
    baseline_rate       DOUBLE PRECISION NOT NULL,
    baseline_off_hours  DOUBLE PRECISION NOT NULL,
    baseline_avg_sens   DOUBLE PRECISION NOT NULL,
    file_reads          INTEGER      NOT NULL,
    api_calls           INTEGER      NOT NULL,
    exports             INTEGER      NOT NULL,
    off_hours_actions   INTEGER      NOT NULL,
    action_count        INTEGER      NOT NULL,
    sens_sum            DOUBLE PRECISION NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE
);

CREATE TABLE agent_tools (
    agent_id VARCHAR(40) NOT NULL REFERENCES agents (id),
    tool     VARCHAR(40) NOT NULL,
    PRIMARY KEY (agent_id, tool)
);

CREATE TABLE agent_allowed (
    agent_id  VARCHAR(40) NOT NULL REFERENCES agents (id),
    category  VARCHAR(40) NOT NULL,
    PRIMARY KEY (agent_id, category)
);

CREATE TABLE agent_restricted (
    agent_id  VARCHAR(40) NOT NULL REFERENCES agents (id),
    category  VARCHAR(40) NOT NULL,
    PRIMARY KEY (agent_id, category)
);

CREATE TABLE agent_restrict_actions (
    agent_id    VARCHAR(40) NOT NULL REFERENCES agents (id),
    action_kind VARCHAR(40) NOT NULL,
    PRIMARY KEY (agent_id, action_kind)
);

CREATE TABLE agent_blocked_resources (
    agent_id VARCHAR(40) NOT NULL REFERENCES agents (id),
    category VARCHAR(40) NOT NULL,
    PRIMARY KEY (agent_id, category)
);

CREATE TABLE agent_baseline_cats (
    agent_id VARCHAR(40)       NOT NULL REFERENCES agents (id),
    category VARCHAR(40)       NOT NULL,
    weight   DOUBLE PRECISION,
    PRIMARY KEY (agent_id, category)
);

CREATE TABLE agent_fingerprint_cats (
    agent_id VARCHAR(40) NOT NULL REFERENCES agents (id),
    category VARCHAR(40) NOT NULL,
    hits     INTEGER     NOT NULL,
    PRIMARY KEY (agent_id, category)
);

CREATE TABLE agent_drift_points (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_id VARCHAR(40) NOT NULL REFERENCES agents (id),
    label    VARCHAR(12) NOT NULL,
    sens     DOUBLE PRECISION NOT NULL
);

-- ---------------------------------------------------------------- event stream

CREATE TABLE action_events (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts               TIMESTAMP WITH TIME ZONE NOT NULL,
    agent_id         VARCHAR(40)  NOT NULL,
    agent_name       VARCHAR(80)  NOT NULL,
    agent_role       VARCHAR(80),
    agent_icon       VARCHAR(8),
    kind             VARCHAR(30)  NOT NULL,
    tool             VARCHAR(60),
    category         VARCHAR(60),
    target           VARCHAR(400),
    message          VARCHAR(500),
    to_agent         VARCHAR(40),
    sensitivity      DOUBLE PRECISION NOT NULL,
    risk_score       INTEGER      NOT NULL,
    decision         VARCHAR(20)  NOT NULL,
    reason           VARCHAR(300),
    factors_json     VARCHAR(4000),
    demo             VARCHAR(40),
    executed         BOOLEAN      NOT NULL,
    execution_detail VARCHAR(2000),
    approval_id      BIGINT
);
CREATE INDEX idx_action_ts ON action_events (ts);
CREATE INDEX idx_action_decision ON action_events (decision);

CREATE TABLE alerts (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts           TIMESTAMP WITH TIME ZONE NOT NULL,
    agent_id     VARCHAR(40)  NOT NULL,
    agent_name   VARCHAR(80)  NOT NULL,
    agent_role   VARCHAR(80),
    agent_icon   VARCHAR(8),
    kind         VARCHAR(30),
    tool         VARCHAR(60),
    category     VARCHAR(60),
    target       VARCHAR(400),
    message      VARCHAR(500),
    risk_score   INTEGER      NOT NULL,
    decision     VARCHAR(20)  NOT NULL,
    reason       VARCHAR(300),
    factors_json VARCHAR(4000),
    status       VARCHAR(16)  NOT NULL,
    containment  VARCHAR(300),
    demo         VARCHAR(40),
    event_id     BIGINT
);
CREATE INDEX idx_alert_status ON alerts (status);

CREATE TABLE agent_comms (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts      TIMESTAMP WITH TIME ZONE NOT NULL,
    from_agent VARCHAR(40) NOT NULL,
    to_agent   VARCHAR(40) NOT NULL,
    message    VARCHAR(500) NOT NULL,
    flagged    BOOLEAN      NOT NULL
);
CREATE INDEX idx_comms_ts ON agent_comms (ts);

CREATE TABLE audit_entries (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts           TIMESTAMP WITH TIME ZONE NOT NULL,
    actor        VARCHAR(64),
    agent        VARCHAR(80),
    role         VARCHAR(80),
    kind         VARCHAR(40),
    description  VARCHAR(500),
    target       VARCHAR(300),
    decision     VARCHAR(20),
    score        INTEGER,
    reason       VARCHAR(300),
    factors_json VARCHAR(4000)
);

-- ---------------------------------------------------------------- governance

CREATE TABLE approvals (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts               TIMESTAMP WITH TIME ZONE NOT NULL,
    agent_id         VARCHAR(40)  NOT NULL,
    agent_name       VARCHAR(80)  NOT NULL,
    event_id         BIGINT,
    kind             VARCHAR(30)  NOT NULL,
    tool             VARCHAR(60),
    category         VARCHAR(60),
    target           VARCHAR(400),
    message          VARCHAR(500),
    risk_score       INTEGER      NOT NULL,
    reason           VARCHAR(300),
    factors_json     VARCHAR(4000),
    status           VARCHAR(16)  NOT NULL,
    decided_by       VARCHAR(64),
    decided_at       TIMESTAMP WITH TIME ZONE,
    decision_note    VARCHAR(300),
    executed_at      TIMESTAMP WITH TIME ZONE,
    execution_detail VARCHAR(2000)
);
CREATE INDEX idx_approval_status ON approvals (status);

CREATE TABLE containment_actions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts            TIMESTAMP WITH TIME ZONE NOT NULL,
    agent_id      VARCHAR(40)  NOT NULL,
    agent_name    VARCHAR(80),
    kind          VARCHAR(24)  NOT NULL,
    detail        VARCHAR(300) NOT NULL,
    trigger_reason VARCHAR(200),
    actor         VARCHAR(64),
    alert_id      BIGINT,
    active        BOOLEAN      NOT NULL
);
CREATE INDEX idx_containment_ts ON containment_actions (ts);

-- ---------------------------------------------------------------- analysis & evidence

CREATE TABLE content_analyses (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts                   TIMESTAMP WITH TIME ZONE NOT NULL,
    actor                VARCHAR(64),
    source_type          VARCHAR(16)  NOT NULL,
    filename             VARCHAR(200),
    content_hash         VARCHAR(64),
    text_excerpt         VARCHAR(600),
    text_length          INTEGER      NOT NULL,
    indicator_count      INTEGER      NOT NULL,
    score                INTEGER      NOT NULL,
    recommendation       VARCHAR(30)  NOT NULL,
    reason               VARCHAR(300),
    indicators_json      VARCHAR(8000),
    affected_agents_json VARCHAR(4000),
    gateway_json         VARCHAR(8000),
    sensitive_values     INTEGER      NOT NULL
);
CREATE INDEX idx_analysis_ts ON content_analyses (ts);

CREATE TABLE uploaded_files (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts            TIMESTAMP WITH TIME ZONE NOT NULL,
    original_name VARCHAR(200) NOT NULL,
    stored_name   VARCHAR(200) NOT NULL,
    content_type  VARCHAR(100),
    size_bytes    BIGINT       NOT NULL,
    sha256        VARCHAR(64),
    uploaded_by   VARCHAR(64),
    kind          VARCHAR(20)
);
CREATE INDEX idx_upload_ts ON uploaded_files (ts);
